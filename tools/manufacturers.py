"""Writes the CSA's manufacturer code list, as ZAP ships it, to a Python module."""

import sys
import urllib.request
import xml.etree.ElementTree as ET

HEADER = '''"""The CSA's Zigbee manufacturer codes and names.

Generated by `make manufacturers` from {url}
Copyright (c) 2008,2022 Silicon Labs, under the Apache License, Version 2.0.
"""

NAMES = {{
'''


def main(url: str, out: str) -> None:
    with urllib.request.urlopen(url, timeout=60) as response:
        root = ET.fromstring(response.read())
    names = {int(m.get("code"), 16): m.get("translation") for m in root.iter("mapping")}
    body = "".join(f"    0x{code:04X}: {name!r},\n" for code, name in sorted(names.items()))
    with open(out, "w") as f:
        f.write(HEADER.format(url=url) + body + "}\n")


if __name__ == "__main__":
    main(*sys.argv[1:])
